/**
 * Expo config plugin that defines Android Auto Backup rules for the app.
 *
 * We do not use the rules that ship with expo-secure-store
 * (`configureAndroidBackup`), because they declare only
 * `<include domain="sharedpref" .../>`. Android treats any `<include>` as
 * opting out of the "back up everything" default, so those rules would drop
 * `files/main.db` and everything under `files/accounts/` from every backup —
 * the opposite of what we want.
 *
 * The two backup paths get different rules because they have very different
 * size limits:
 *
 *  - Cloud backup (Google Drive) is capped at 25 MB per app, and the system
 *    skips the backup entirely when an app exceeds it. Archive media alone
 *    routinely runs to hundreds of MB, so including `accounts/` would mean no
 *    cloud backup at all — not even the small `main.db`. Cloud backup
 *    therefore covers app-level data only, so a cloud restore still brings
 *    back the account list and settings.
 *
 *  - Device-to-device transfer (the path Android's setup wizard uses when
 *    migrating to a new phone) allows roughly 2 GB, so it carries the full
 *    archive.
 *
 * `full-backup-content` applies to Android 11 and lower, which has no
 * device-transfer path, so it mirrors the cloud rules.
 *
 * SecureStore is excluded everywhere: its shared_prefs entries are encrypted
 * with a hardware-backed Keystore key that never leaves the device, so a
 * restored copy would be undecryptable.
 */
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

/** Resource names, referenced from the manifest as `@xml/<name>`. */
const BACKUP_RULES_RESOURCE = "cyd_backup_rules";
const DATA_EXTRACTION_RULES_RESOURCE = "cyd_data_extraction_rules";

/**
 * Account archives (`data.db` plus downloaded media) live here, under the
 * `file` domain. Excluded from cloud backup for quota reasons only.
 */
const ACCOUNTS_PATH = "accounts";

/** expo-secure-store's SharedPreferences file, holding encrypted credentials. */
const SECURE_STORE_PREFS = "SecureStore";

const BACKUP_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/android-backup-rules.js. Do not edit by hand. -->
<!-- Auto Backup configuration for Android 11 and lower (cloud backup only). -->
<full-backup-content>
  <include domain="file" path="."/>
  <include domain="sharedpref" path="."/>
  <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}"/>
  <exclude domain="file" path="${ACCOUNTS_PATH}"/>
</full-backup-content>
`;

const DATA_EXTRACTION_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/android-backup-rules.js. Do not edit by hand. -->
<!-- Auto Backup configuration for Android 12 and higher. -->
<data-extraction-rules>
  <!-- Capped at 25 MB, so archives are left out to keep backups running. -->
  <cloud-backup>
    <include domain="file" path="."/>
    <include domain="sharedpref" path="."/>
    <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}"/>
    <exclude domain="file" path="${ACCOUNTS_PATH}"/>
  </cloud-backup>
  <!-- Roughly 2 GB, so the full archive comes across to the new device. -->
  <device-transfer>
    <include domain="file" path="."/>
    <include domain="database" path="."/>
    <include domain="sharedpref" path="."/>
    <exclude domain="sharedpref" path="${SECURE_STORE_PREFS}"/>
  </device-transfer>
</data-extraction-rules>
`;

/**
 * Write the rule resources into the generated Android project.
 *
 * @param {import("expo/config").ExpoConfig} config
 */
function withBackupRuleResources(config) {
  return withDangerousMod(config, [
    "android",
    async (config) => {
      const xmlDir = path.join(
        config.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
        "xml",
      );
      await fs.promises.mkdir(xmlDir, { recursive: true });
      await fs.promises.writeFile(
        path.join(xmlDir, `${BACKUP_RULES_RESOURCE}.xml`),
        BACKUP_RULES_XML,
        "utf8",
      );
      await fs.promises.writeFile(
        path.join(xmlDir, `${DATA_EXTRACTION_RULES_RESOURCE}.xml`),
        DATA_EXTRACTION_RULES_XML,
        "utf8",
      );
      return config;
    },
  ]);
}

/**
 * Point the manifest at our rule resources. `android:allowBackup` itself is
 * set through `android.allowBackup` in app.config.ts.
 *
 * @param {import("expo/config").ExpoConfig} config
 */
function withBackupManifestAttributes(config) {
  return withAndroidManifest(config, (config) => {
    const application = config.modResults?.manifest?.application?.[0];

    if (!application) {
      throw new Error(
        "android-backup-rules: no <application> element in AndroidManifest.xml",
      );
    }

    if (!application.$) {
      application.$ = {};
    }

    application.$["android:fullBackupContent"] = `@xml/${BACKUP_RULES_RESOURCE}`;
    application.$["android:dataExtractionRules"] =
      `@xml/${DATA_EXTRACTION_RULES_RESOURCE}`;

    return config;
  });
}

/**
 * @param {import("expo/config").ExpoConfig} config
 */
function withAndroidBackupRules(config) {
  return withBackupManifestAttributes(withBackupRuleResources(config));
}

module.exports = withAndroidBackupRules;
module.exports.BACKUP_RULES_XML = BACKUP_RULES_XML;
module.exports.DATA_EXTRACTION_RULES_XML = DATA_EXTRACTION_RULES_XML;
